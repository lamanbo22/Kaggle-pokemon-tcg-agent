"""One shared policy with deck conditioning and a dynamic own-hand adapter."""
from __future__ import annotations
import math
from dataclasses import asdict
from typing import Any
import numpy as np
import torch
from torch import nn
from torch.nn import functional as F
from policy_bridge.shared_schema_primitives import FEATURE_SEMANTICS_VERSION, EntityKind, RelativeOwner, Zone
from policy_bridge.episode_archive.card_repository_index import CARD_FEATURE_DIM
from policy_bridge.action_predictors.game_card_representation_service import CardEncoder, SetPool
from policy_bridge.decision_message_contract import FeatureSpec

def _embedding(size: int, dimension: int) -> nn.Embedding:
    return nn.Embedding(size, dimension, padding_idx=0)

class HandConditionedAdapter(nn.Module):
    """Shared bottleneck whose FiLM parameters are generated by the current hand set."""

    def __init__(self, dimension: int, bottleneck: int):
        super().__init__()
        self.down = nn.Linear(dimension, bottleneck)
        self.up = nn.Linear(bottleneck, dimension)
        self.condition = nn.Linear(dimension, dimension * 2)
        self.norm = nn.LayerNorm(dimension)

    def forward(self, value: torch.Tensor, hand: torch.Tensor) -> torch.Tensor:
        scale, bias = self.condition(hand).chunk(2, dim=-1)
        delta = self.up(F.gelu(self.down(value)))
        while scale.ndim < value.ndim:
            scale = scale.unsqueeze(1)
            bias = bias.unsqueeze(1)
        return self.norm(value + torch.sigmoid(scale) * delta + 0.1 * torch.tanh(bias))

class UnifiedPolicy(nn.Module):
    """Entity/event Transformer and autoregressive legal-option pointer."""

    def __init__(self, model_config: dict[str, Any], feature_spec: FeatureSpec, card_features: np.ndarray | torch.Tensor | None=None):
        super().__init__()
        self.model_config = dict(model_config)
        self.feature_spec = feature_spec
        d_model = int(model_config.get('d_model', 192))
        card_dim = int(model_config.get('card_embedding_dim', 96))
        heads = int(model_config.get('attention_heads', 6))
        dropout = float(model_config.get('dropout', 0.05))
        card_vocab = int(model_config.get('card_vocab_size', 1268))
        attack_vocab = int(model_config.get('attack_vocab_size', 1557))
        event_gru_layers = int(model_config.get('event_gru_layers', 2))
        if not event_gru_layers < 1:
            pass
        else:
            raise ValueError('event_gru_layers must be at least 1')
        if not card_features is None:
            pass
        else:
            card_features = torch.zeros(card_vocab, CARD_FEATURE_DIM)
        static = torch.as_tensor(card_features, dtype=torch.float32)
        self.d_model = d_model
        self.card_encoder = CardEncoder(card_vocab, card_dim, d_model, static)
        self.deck_pool = SetPool(d_model)
        self.known_pool = SetPool(d_model)
        self.global_embeddings = nn.ModuleList([_embedding(size, d_model) for size in (16, 65, 4, 18, 18)])
        self.global_numeric = nn.Sequential(nn.Linear(16, d_model), nn.GELU(), nn.Linear(d_model, d_model))
        self.global_norm = nn.LayerNorm(d_model)
        self.entity_embeddings = nn.ModuleList([nn.Identity(), _embedding(14, d_model), _embedding(4, d_model), _embedding(16, d_model), _embedding(5, d_model)])
        self.entity_numeric = nn.Sequential(nn.Linear(9, d_model), nn.GELU(), nn.Linear(d_model, d_model))
        self.entity_norm = nn.LayerNorm(d_model)
        self.event_embeddings = nn.ModuleList([_embedding(257, d_model), _embedding(4, d_model), nn.Identity(), nn.Identity(), _embedding(attack_vocab, d_model), _embedding(16, d_model), _embedding(16, d_model), _embedding(65, d_model)])
        self.event_numeric = nn.Linear(3, d_model)
        self.event_norm = nn.LayerNorm(d_model)
        self.event_gru = nn.GRU(d_model, d_model, num_layers=event_gru_layers, batch_first=True, dropout=0.0 if not event_gru_layers > 1 else dropout)
        encoder_layer = nn.TransformerEncoderLayer(d_model=d_model, nhead=heads, dim_feedforward=int(model_config.get('ffn_dim', 768)), dropout=dropout, activation='gelu', batch_first=True, norm_first=True)
        self.board_encoder = nn.TransformerEncoder(encoder_layer, num_layers=int(model_config.get('transformer_layers', 6)), norm=nn.LayerNorm(d_model), enable_nested_tensor=False)
        self.deck_film = nn.Linear(d_model, d_model * 2)
        self.hand_pool = SetPool(d_model)
        self.hand_adapter = HandConditionedAdapter(d_model, int(model_config.get('hand_adapter_dim', 48)))
        self.option_embeddings = nn.ModuleList([_embedding(65, d_model), _embedding(16, d_model), _embedding(4, d_model), _embedding(16, d_model), _embedding(17, d_model), nn.Identity(), nn.Identity(), nn.Identity(), nn.Identity(), _embedding(attack_vocab, d_model), _embedding(65, d_model), _embedding(65, d_model), _embedding(16, d_model), _embedding(16, d_model)])
        self.option_card_roles = nn.Parameter(torch.ones(4, d_model))
        self.option_numeric = nn.Sequential(nn.Linear(4, d_model), nn.GELU(), nn.Linear(d_model, d_model))
        self.option_norm = nn.LayerNorm(d_model)
        self.option_cross_attention = nn.MultiheadAttention(d_model, heads, dropout=dropout, batch_first=True)
        option_layer = nn.TransformerEncoderLayer(d_model=d_model, nhead=heads, dim_feedforward=int(model_config.get('ffn_dim', 768)), dropout=dropout, activation='gelu', batch_first=True, norm_first=True)
        self.option_encoder = nn.TransformerEncoder(option_layer, num_layers=int(model_config.get('option_layers', 2)), norm=nn.LayerNorm(d_model), enable_nested_tensor=False)
        self.option_adapter = HandConditionedAdapter(d_model, int(model_config.get('hand_adapter_dim', 48)))
        self.base_scorer = nn.Sequential(nn.Linear(d_model * 3, d_model), nn.GELU(), nn.Linear(d_model, 1))
        self.decoder_query = nn.Linear(d_model, d_model, bias=False)
        self.option_key = nn.Linear(d_model, d_model, bias=False)
        self.decoder_cell = nn.GRUCell(d_model, d_model)
        self.stop_head = nn.Sequential(nn.Linear(d_model * 2, d_model), nn.GELU(), nn.Linear(d_model, 1))
        self.value_head = nn.Sequential(nn.Linear(d_model, d_model), nn.GELU(), nn.Linear(d_model, 1), nn.Tanh())

    def forward(self, batch: dict[str, torch.Tensor], actions: torch.Tensor | None=None, equivalence: bool=False, temperature: float=1.0) -> dict[str, torch.Tensor]:
        return self.sequence_stats(batch, actions, equivalence=equivalence, temperature=temperature)

    def encode(self, batch: dict[str, torch.Tensor]) -> dict[str, torch.Tensor]:
        global_cat = batch['global_cat'].long()
        global_token = self.global_numeric(batch['global_num'].float())
        for index, embedding in enumerate(self.global_embeddings):
            global_token = global_token + embedding(global_cat[:, index])
        own_deck_ids = batch['own_deck'].long()
        own_deck_values = self.card_encoder(own_deck_ids)
        deck_token = self.deck_pool(own_deck_values, own_deck_ids.ne(0))
        known_ids = batch['known_cards'].long()
        known_values = self.card_encoder(known_ids)
        known_token = self.known_pool(known_values, known_ids.ne(0))
        gamma, beta = self.deck_film(deck_token).chunk(2, dim=-1)
        global_token = self.global_norm((1.0 + 0.1 * torch.tanh(gamma)) * global_token + 0.1 * beta)
        entity_cat = batch['entity_cat'].long()
        entity_token = self.card_encoder(entity_cat[:, :, 0])
        for index in range(1, len(self.entity_embeddings)):
            entity_token = entity_token + self.entity_embeddings[index](entity_cat[:, :, index])
        entity_token = self.entity_norm(entity_token + self.entity_numeric(batch['entity_num'].float()))
        entity_mask = _length_mask(batch['entity_count'], entity_cat.shape[1])
        entity_token = entity_token.masked_fill(~entity_mask.unsqueeze(-1), 0.0)
        event_cat = batch['event_cat'].long()
        event_token = self.card_encoder(event_cat[:, :, 2])
        event_token = event_token + self.card_encoder(event_cat[:, :, 3])
        for index in (0, 1, 4, 5, 6, 7):
            event_token = event_token + self.event_embeddings[index](event_cat[:, :, index])
        event_token = self.event_norm(event_token + self.event_numeric(batch['event_num'].float()))
        event_output, _ = self.event_gru(event_token)
        event_count = batch['event_count'].long()
        gather_index = (event_count - 1).clamp_min(0)
        history_token = event_output[torch.arange(event_output.shape[0], device=event_output.device), gather_index]
        history_token = history_token * event_count.gt(0).unsqueeze(-1)
        prefix = torch.stack([global_token, history_token, deck_token, known_token], dim=1)
        board_input = torch.cat([prefix, entity_token], dim=1)
        prefix_mask = torch.ones(entity_mask.shape[0], 4, dtype=torch.bool, device=entity_mask.device)
        board_mask = torch.cat([prefix_mask, entity_mask], dim=1)
        board = self.board_encoder(board_input, src_key_padding_mask=~board_mask)
        state = board[:, 0]
        hand_mask = entity_mask & entity_cat[:, :, 1].eq(int(Zone.HAND)) & entity_cat[:, :, 2].eq(int(RelativeOwner.SELF))
        hand = self.hand_pool(entity_token, hand_mask)
        state = self.hand_adapter(state, hand)
        option_cat = batch['option_cat'].long()
        option_token = torch.zeros(*option_cat.shape[:2], self.d_model, device=option_cat.device, dtype=state.dtype)
        for index in (0, 1, 2, 3, 4, 9, 10, 11, 12, 13):
            option_token = option_token + self.option_embeddings[index](option_cat[:, :, index])
        for role, index in enumerate((5, 6, 7, 8)):
            option_token = option_token + self.card_encoder(option_cat[:, :, index]) * self.option_card_roles[role]
        option_token = self.option_norm(option_token + self.option_numeric(batch['option_num'].float()))
        option_mask = _length_mask(batch['option_count'], option_cat.shape[1])
        cross, _ = self.option_cross_attention(option_token, board, board, key_padding_mask=~board_mask, need_weights=False)
        option_token = self.option_encoder(option_token + cross, src_key_padding_mask=~option_mask)
        option_token = self.option_adapter(option_token, hand)
        option_token = option_token.masked_fill(~option_mask.unsqueeze(-1), 0.0)
        return {'state': state, 'options': option_token, 'option_mask': option_mask, 'value': self.value_head(state).squeeze(-1)}

    def pointer_logits(self, encoded: dict[str, torch.Tensor], decoder: torch.Tensor, selected: torch.Tensor, selected_count: torch.Tensor, min_count: torch.Tensor, max_count: torch.Tensor) -> torch.Tensor:
        state = encoded['state']
        options = encoded['options']
        state_expanded = state.unsqueeze(1).expand_as(options)
        base = self.base_scorer(torch.cat([state_expanded, options, state_expanded * options], dim=-1)).squeeze(-1)
        pointer = (self.decoder_query(decoder).unsqueeze(1) * self.option_key(options)).sum(dim=-1) / math.sqrt(self.d_model)
        option_logits = base + pointer
        valid_options = encoded['option_mask'] & ~selected
        option_logits = option_logits.masked_fill(~valid_options, -torch.inf)
        stop = self.stop_head(torch.cat([state, decoder], dim=-1)).squeeze(-1)
        stop_allowed = selected_count.ge(min_count)
        stop = stop.masked_fill(~stop_allowed, -torch.inf)
        force_stop = selected_count.ge(max_count)
        option_logits = option_logits.masked_fill(force_stop.unsqueeze(-1), -torch.inf)
        return torch.cat([option_logits, stop.unsqueeze(-1)], dim=-1)

    def sequence_stats(self, batch: dict[str, torch.Tensor], actions: torch.Tensor | None=None, *, equivalence: bool=False, temperature: float=1.0) -> dict[str, torch.Tensor]:
        encoded = self.encode(batch)
        actions = actions if not actions is None else batch['actions']
        actions = actions.long()
        batch_size, option_slots = encoded['option_mask'].shape
        action_count = batch['action_count'].long()
        min_count = batch['min_count'].long()
        max_count = batch['max_count'].long()
        decoder = encoded['state']
        selected = torch.zeros_like(encoded['option_mask'])
        selected_count = torch.zeros(batch_size, dtype=torch.long, device=actions.device)
        log_probability = torch.zeros(batch_size, device=actions.device)
        entropy = torch.zeros(batch_size, device=actions.device)
        token_count = torch.zeros(batch_size, device=actions.device)
        maximum_steps = int(action_count.max().item()) + 1
        initial_logits: torch.Tensor | None = None
        sequence_logits = []
        sequence_mask = []
        for step in range(maximum_steps):
            active = step <= action_count
            logits = self.pointer_logits(encoded, decoder, selected, selected_count, min_count, max_count)
            if not step == 0:
                pass
            else:
                initial_logits = logits
            sequence_logits.append(logits)
            sequence_mask.append(active)
            scaled = logits / max(float(temperature), 1e-06)
            log_probs = F.log_softmax(scaled, dim=-1)
            probs = log_probs.exp()
            entropy = entropy + torch.where(active, -(probs * torch.nan_to_num(log_probs, neginf=0.0)).sum(dim=-1), torch.zeros_like(entropy))
            target = torch.where(step < action_count, actions[:, step], torch.full_like(action_count, option_slots))
            step_log_prob = log_probs.gather(1, target.unsqueeze(1)).squeeze(1)
            if not (equivalence and step < actions.shape[1]):
                pass
            else:
                is_option = step < action_count
                rows = is_option.nonzero(as_tuple=False).flatten()
                if not rows.numel():
                    pass
                else:
                    target_index = actions[:, step].clamp_min(0)
                    equivalent = self._equivalent_option_mask(batch, target_index)
                    equivalent = equivalent & ~selected & encoded['option_mask']
                    mass = torch.logsumexp(log_probs[rows, :option_slots].masked_fill(~equivalent[rows], -torch.inf), dim=-1)
                    step_log_prob = step_log_prob.index_copy(0, rows, mass)
            log_probability = log_probability + torch.where(active, step_log_prob, torch.zeros_like(step_log_prob))
            token_count = token_count + active
            choose = active & (step < action_count)
            chosen_index = actions[:, step].clamp(0, option_slots - 1)
            chosen_value = encoded['options'][torch.arange(batch_size, device=actions.device), chosen_index]
            updated = self.decoder_cell(chosen_value, decoder)
            decoder = torch.where(choose.unsqueeze(-1), updated, decoder)
            selected = selected.scatter(1, chosen_index.unsqueeze(1), choose.unsqueeze(1))
            selected_count = selected_count + choose.long()
        return {**encoded, 'initial_logits': initial_logits, 'sequence_logits': torch.stack(sequence_logits, dim=1), 'sequence_mask': torch.stack(sequence_mask, dim=1), 'log_probability': log_probability, 'entropy': entropy / token_count.clamp_min(1), 'token_count': token_count}

    @torch.no_grad()
    def act(self, batch: dict[str, torch.Tensor], *, temperature: float=0.0, generator: torch.Generator | None=None) -> dict[str, torch.Tensor]:
        encoded = self.encode(batch)
        batch_size, option_slots = encoded['option_mask'].shape
        max_action_slots = batch['actions'].shape[1]
        output = torch.full((batch_size, max_action_slots), -1, dtype=torch.long, device=encoded['state'].device)
        counts = torch.zeros(batch_size, dtype=torch.long, device=output.device)
        selected = torch.zeros_like(encoded['option_mask'])
        decoder = encoded['state']
        stopped = torch.zeros(batch_size, dtype=torch.bool, device=output.device)
        log_probability = torch.zeros(batch_size, device=output.device)
        entropy = torch.zeros(batch_size, device=output.device)
        entropy_steps = torch.zeros(batch_size, device=output.device)
        min_count = batch['min_count'].long()
        max_count = batch['max_count'].long().clamp_max(max_action_slots)
        initial_logits: torch.Tensor | None = None
        for step in range(max_action_slots + 1):
            if not bool(stopped.all()):
                pass
            else:
                break
            logits = self.pointer_logits(encoded, decoder, selected, counts, min_count, max_count)
            if not step == 0:
                pass
            else:
                initial_logits = logits
            active = ~stopped
            if not temperature <= 0:
                scaled = logits / temperature
                log_probs = F.log_softmax(scaled, dim=-1)
                choice = torch.multinomial(log_probs.exp(), 1, generator=generator).squeeze(1)
            else:
                choice = logits.argmax(dim=-1)
                log_probs = F.log_softmax(logits, dim=-1)
            probs = log_probs.exp()
            step_entropy = -(probs * torch.nan_to_num(log_probs, neginf=0.0)).sum(dim=-1)
            log_probability += torch.where(active, log_probs.gather(1, choice.unsqueeze(1)).squeeze(1), torch.zeros_like(log_probability))
            entropy += torch.where(active, step_entropy, torch.zeros_like(step_entropy))
            entropy_steps += active
            chose_stop = choice.eq(option_slots)
            choose_option = active & ~chose_stop
            if not step < max_action_slots:
                pass
            else:
                output[:, step] = torch.where(choose_option, choice, output[:, step])
            chosen_index = choice.clamp_max(option_slots - 1)
            chosen_value = encoded['options'][torch.arange(batch_size, device=output.device), chosen_index]
            updated = self.decoder_cell(chosen_value, decoder)
            decoder = torch.where(choose_option.unsqueeze(-1), updated, decoder)
            selected.scatter_(1, chosen_index.unsqueeze(1), choose_option.unsqueeze(1))
            counts += choose_option.long()
            stopped |= active & (chose_stop | counts.ge(max_count))
        return {'actions': output, 'action_count': counts, 'log_probability': log_probability, 'entropy': entropy / entropy_steps.clamp_min(1), 'value': encoded['value'], 'state': encoded['state'], 'options': encoded['options'], 'option_mask': encoded['option_mask'], 'initial_logits': initial_logits}

    @staticmethod
    def _equivalent_option_mask(batch: dict[str, torch.Tensor], target_index: torch.Tensor) -> torch.Tensor:
        rows = torch.arange(target_index.shape[0], device=target_index.device)
        target_cat = batch['option_cat'][rows, target_index].unsqueeze(1)
        target_num = batch['option_num'][rows, target_index].unsqueeze(1)
        same_cat = batch['option_cat'].eq(target_cat).all(dim=-1)
        same_num = batch['option_num'].eq(target_num).all(dim=-1)
        return same_cat & same_num

    def checkpoint_metadata(self) -> dict[str, Any]:
        return {'model_config': self.model_config, 'feature_spec': asdict(self.feature_spec), 'feature_semantics_version': FEATURE_SEMANTICS_VERSION}

def build_policy(model_config: dict[str, Any], feature_spec: FeatureSpec, card_features: np.ndarray | torch.Tensor | None=None) -> UnifiedPolicy:
    """Instantiate the pre-registered architecture encoded in model config."""
    architecture = str(model_config.get('architecture', 'transformer_v1'))
    if not architecture == 'transformer_v1':
        pass
    else:
        return UnifiedPolicy(model_config, feature_spec, card_features)
    if architecture == 'semantic_minimal_v1':
        from policy_bridge.action_predictors.behavioral_contract_essential_decision_policy import SemanticMinimalPolicy
        return SemanticMinimalPolicy(model_config, feature_spec, card_features)
    raise ValueError(f'unsupported policy architecture: {architecture}')

def _length_mask(lengths: torch.Tensor, maximum: int) -> torch.Tensor:
    return torch.arange(maximum, device=lengths.device).unsqueeze(0) < lengths.long().unsqueeze(1)

def batch_to_torch(batch: dict[str, np.ndarray | torch.Tensor], device: torch.device | str | None=None) -> dict[str, torch.Tensor]:
    result = {}
    for name, value in batch.items():
        tensor = value if isinstance(value, torch.Tensor) else torch.from_numpy(value)
        result[name] = tensor.to(device=device, non_blocking=True) if device is not None else tensor
    return result
